/**
 * ブロック枠の「用事名」（2026-09-04 宗本さんの要望）。
 *
 * 予定表の灰色の枠が「—」としか出ず、自分で入れたのに何のブロックか分からなかった。
 * 「面談」「掃除」「設営」のように名前を付けて、ひと目で分かるようにする。
 *
 * ## 🔴 これはお店の中だけのもの
 *
 * 宗本さん:「ブロックの用事をもちろんお客様には見せません。お店の中だけで見返せる
 * ようにしたいだけです」。オーナーは私的な用事や第三者の名前を書くので、
 * **画面に出さないだけでは足りない。** `blocked_slots` の SELECT ポリシーから
 * お客様を外すところまでやって初めて「見えません」と言える
 * （マイグレーション 20260904020000_blocked_slot_purpose.sql）。
 *
 * ## 🔴 古いアプリは、いまも「ブロック（14:15〜15:15）」を書き続ける
 *
 * この機能より前のクライアントは、人が名前を付ける代わりに
 * `t("schedule.blockReason")` で作った文字列を `reason` に必ず入れていた。
 * iOS 1.6.9 も Android の現行版もそれをやる。**更新されるまで書き込みは止まらない。**
 *
 * そのまま用事名として出すと、予定表の狭いマスでは「ブロ…」になって
 * **いまより読めなくなる**。なので表示の手前で1枚かませる（`blockPurposeName`）。
 * DB を1回掃除するだけでは足りない ── 掃除したそばから古い端末が書き足すため。
 */

/**
 * 入力欄で許す長さ。
 *
 * 全文が読めるのは解除ダイアログとスマホのカード（375px で約20文字）だけ。
 * 週の帯は3〜12文字、日別の表は2〜5文字しか出ないので、これ以上許しても
 * 打った本人にしか分からない文字列が増えるだけ。
 */
export const BLOCK_PURPOSE_MAX = 20;

/**
 * DB の CHECK。**入力欄の上限（20）とわざと違う。**
 *
 * 古いアプリが書く自動生成の文字列は英語で19文字（`Block (14:15–15:15)`）。
 * ここを20にすると、文言を1文字足しただけで**古い端末のブロック作成が黙って失敗する**。
 * 出回っている版に対して DB 側を厳しくしない。
 */
export const BLOCK_PURPOSE_DB_MAX = 30;

/**
 * 古いアプリの自動生成 `reason` の「形」。
 *
 * 文言そのものではなく**形**で見る。5言語のどれを直しても外れない
 * （`ブロック（14:15〜15:15）` / `Block (14:15–15:15)` / `차단 (14:15~15:15)` /
 *  `封锁（14:15〜15:15）` / `封鎖（14:15〜15:15）`）。
 *
 * ⚠️ 「時刻が含まれる」ではなく「**丸ごとこの形**」で判定する。
 *    前者だと「掃除 10:00〜11:00」のような人の入力まで消してしまう。
 *    それでも「掃除（10:00〜11:00）」と括弧付きで書かれると誤判定する。
 *    そのときは絵が消えるのではなく既定の「ブロック」表示に戻るだけで、
 *    DB の文字列は残る（打ち直せば直る）。この程度の取りこぼしは受け入れる。
 */
const GENERATED = /^\S{1,12}\s*[（(]\s*\d{1,2}:\d{2}\s*[〜~–—-]\s*\d{1,2}:\d{2}\s*[)）]$/;

/**
 * 予定表に出す用事名。**人が付けた名前でなければ空文字。**
 *
 * 空のときは呼び出し側が既定の「ブロック」表示に倒すこと
 * （ここで既定文言を返さないのは、`src/lib` から i18n を引かないため）。
 */
export const blockPurposeName = (reason: string | null | undefined): string => {
  const s = (reason ?? "").trim();
  return GENERATED.test(s) ? "" : s;
};
