--   連絡なしの無断キャンセルでも、ペナルティはなし
--
-- ── 実装を調べて分かったこと ──────────────────────────────────
--
-- **「解除する設定」はほとんど無かった。**
--
--   キャンセル料の仕組み        … **存在しない**
--   キャンセル期限の仕組み      … **存在しない**（キャンセルはいつでも可能）
--   無断キャンセルの仕組み      … **存在しない**
--   当日キャンセルの消化扱い    … tenants.same_day_cancel_penalty_enabled で切替可。
--                                 **Salute はもともと false だった**
--
-- つまり**挙動は既に希望どおり**で、足りないのは「そうだとお客様に伝える場所」だった。
-- キャンセル画面には「予約をキャンセルしますか？」としか出ておらず、
-- ペナルティが無いことは**どこにも書いていない。**
--
-- ⚠️ 「前日まで」という文言は本文中にあるが、**あれは予約の締切**
--    （いつまでに予約できるか）であって、キャンセル期限ではない。混同しないこと。
--    tenants.booking_cutoff_type / booking_cutoff_hours が持っている別の設定で、
--    今回は触っていない。
