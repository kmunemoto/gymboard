-- ----------------------------------------------------------------------------
-- キャンセルについての案内（ジムごと）
-- ----------------------------------------------------------------------------
-- NULL / 空 = 何も表示しない（これまでどおりの見た目）。
-- 既定の文章を用意して勝手に出すことは**しない**。
-- ペナルティの有無は店ごとに違うので、上流が代弁すると事実と食い違う。

ALTER TABLE public.tenants
  ADD COLUMN IF NOT EXISTS cancel_policy_body text;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM pg_constraint WHERE conname = 'tenants_cancel_policy_body_len'
  ) THEN
    ALTER TABLE public.tenants
      ADD CONSTRAINT tenants_cancel_policy_body_len
      CHECK (cancel_policy_body IS NULL OR char_length(cancel_policy_body) <= 500);
  END IF;
END $$;

COMMENT ON COLUMN public.tenants.cancel_policy_body IS
  'お客様に見せるキャンセルについての案内。NULL/空なら何も表示しない。'
  '既定文を持たせないこと（ペナルティの有無は店ごとに違い、上流が代弁すると事実と食い違う）。';
