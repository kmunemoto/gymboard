/**
 * 「その日は1枠も取れない」をカレンダー上で判定する。
 *
 * ## なぜ要るか（2026-09-20 宗本さんの要望）
 *
 * > 撮れる枠が無くなった日にちは薄くして、他みたいにそもそもその日は押せない仕様にして。
 * > また枠が空いたら予約が取れる様に数字を黒くして日にちを押せる様にして。
 *
 * それまでは、全枠が「満枠」の日でもカレンダーの数字は黒く、押せてしまっていた。
 * 押すと下に枠が並ぶが**全部「満枠」**で、お客様は何度も日付を押して確かめることになる。
 * 定休日・受付終了日は既に薄くなっていたので、**同じ見た目に揃える**のが要望。
 *
 * ## 🔴 状態を持たない（ここが肝）
 *
 * 「満枠になった日」をどこにも保存しない。**毎回その場で数え直す。**
 * そうすれば、キャンセルが出て枠が1つ空いた瞬間に、次にカレンダーを描いたときには
 * 自動で押せる日に戻る（要望の後半そのもの）。
 * 保存してしまうと「空いたのに押せないまま」を人が直す運用になり、必ず腐る。
 *
 * ## 何を「取れない」と数えるか
 *
 *   数える   … 満枠（同時受入数・担当の重なり）／受付しない時間帯
 *   数えない … **予約の締切**（当日は締切済みでも「空き状況を見せる」ため開けてある。
 *              2026-09-05 の決定。ここで締切を数えると当日が押せなくなり、
 *              「その日に予約している人には空き状況を見せる」が壊れる）
 *   数えない … **プランの残り回数**。これは日付ではなく**その人**の事情。
 *              数えると、回数を使い切った人はカレンダーが全部灰色になり、
 *              空き状況すら見られなくなる。
 *
 * 判定そのもの（満枠か・受付しない時間帯か）は呼ぶ側から関数で渡す。
 * ここに条件を写すと、枠一覧の判定とズレて
 * 「カレンダーは押せるのに枠が全部満枠」「押せないのに実は空いている」が起きる。
 */

/**
 * その日が「1枠も取れない日」か。
 *
 * @param slotStarts その日に出る枠の開始時刻（分）。営業時間・定休日・担当のシフトを
 *   反映済みのものを渡す。**空配列なら false** を返す
 *   （枠が0の日＝定休日などは、別の判定で既に選べなくなっている。
 *     ここで true にすると「なぜ押せないか」の理由が二重になり、
 *     文言の出し分けを誤る）。
 * @param isTakenAt その開始時刻が埋まっている／受け付けていないか。
 */
export const isDayFullyBooked = (
  slotStarts: readonly number[] | null | undefined,
  isTakenAt: (startMinutes: number) => boolean,
): boolean => {
  if (!slotStarts || slotStarts.length === 0) return false;
  return slotStarts.every((m) => isTakenAt(m));
};
