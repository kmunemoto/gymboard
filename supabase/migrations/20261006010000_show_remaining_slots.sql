-- ============================================================================
-- お客様の予約カレンダーに「残り枠」を出すか（ジムごと ON/OFF）
--
-- 2026-10-06 宗本さん:
--   「お客様側の予約サイトで各日にちが残り何枠空いているかリアルタイムで表示される
--     機能を追加して」
--
-- ON のジムだけ、日付の下に「残N」（その日あと何回入れられるか）・満枠の日に「満」を出し、
-- 予約画面を開いている間は1分ごとに空き状況を読み直す。
-- 数え方は src/lib/dayRemainingSlots.ts（開始時刻の数ではなく、入れられる回数）。
--
-- **既定 false（今まで通り）**。空き具合はジムの混み具合そのものなので、
-- 見せるかどうかはジムが決める。特定のジムの値はここに書かない（リポジトリは public）。
-- ============================================================================

ALTER TABLE public.tenants
  ADD COLUMN IF NOT EXISTS show_remaining_slots boolean NOT NULL DEFAULT false;

COMMENT ON COLUMN public.tenants.show_remaining_slots IS
  'お客様の予約カレンダーに残り枠（残N／満）を出すか。既定 false';
